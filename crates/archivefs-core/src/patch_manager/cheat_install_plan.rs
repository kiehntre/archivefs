/// Which identity the installed filename was taken from. Always reported,
/// never guessed silently.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CheatDestinationNameSource {
    /// The content file's own basename - what RetroArch shows as the
    /// content name, and therefore the name it looks for.
    ContentBasename,
    /// The playlist/database label for this content.
    PlaylistName,
    /// The catalogue file's own name, used only when nothing stronger is
    /// available.
    CatalogueName,
}

impl CheatDestinationNameSource {
    #[must_use]
    pub fn label(self) -> &'static str {
        match self {
            Self::ContentBasename => "content filename",
            Self::PlaylistName => "playlist entry name",
            Self::CatalogueName => "catalogue file name",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CheatDestinationRequest {
    /// The selected profile's own resolved cheat directory. Never a default
    /// this module invents.
    pub profile_cheat_root: PathBuf,
    /// The archive's platform, in any recognized spelling.
    pub platform: Option<String>,
    /// The content file's basename without extension.
    pub content_basename: Option<String>,
    /// The playlist/database label, when one is known.
    pub playlist_name: Option<String>,
    /// The chosen candidate's own display name.
    pub catalogue_name: String,
}

/// Where the platform subdirectory name came from. A real RetroArch cheat
/// directory is laid out by libretro *database* name ("Nintendo - Nintendo
/// Entertainment System"), not by this project's canonical short name
/// ("NES"), so which one was used has to be visible.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CheatPlatformDirectorySource {
    /// A directory that already exists in the profile's cheat root and
    /// resolves to this same platform - the layout RetroArch itself ships
    /// and the user already browses.
    ExistingProfileDirectory,
    /// No matching directory exists yet, so the canonical platform name is
    /// used and the directory is created.
    CanonicalPlatformName,
}

impl CheatPlatformDirectorySource {
    #[must_use]
    pub fn label(self) -> &'static str {
        match self {
            Self::ExistingProfileDirectory => "existing RetroArch cheat directory",
            Self::CanonicalPlatformName => "canonical platform name (new directory)",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedCheatDestination {
    pub path: PathBuf,
    pub platform_directory: String,
    pub platform_directory_source: CheatPlatformDirectorySource,
    pub file_name: String,
    pub name_source: CheatDestinationNameSource,
    /// What is at the destination right now.
    pub state: DestinationState,
    /// True when installing replaces existing content.
    pub replaces_existing: bool,
}

/// Resolves `<profile cheat root>/<canonical platform>/<name>.cht`.
///
/// This is the libretro layout RetroArch's own cheat-file browser opens
/// into, so an installed file is reachable through Quick Menu -> Cheats ->
/// Load Cheat File without the user navigating elsewhere.
///
/// The platform directory is only ever this project's own canonical name;
/// an unrecognized platform is an error, never a sanitized passthrough of
/// untrusted text. The filename comes from the strongest available
/// identity, and which one was used is always reported so the user can see
/// it before confirming.
///
/// Path traversal, symlinked parents, symlinked destinations, and anything
/// resolving outside the profile's cheat directory are rejected by
/// [`assess_destination`] - the same checks every other adapter's
/// destinations go through.
pub fn resolve_cheat_destination(
    request: &CheatDestinationRequest,
) -> Result<ResolvedCheatDestination, CheatInstallPlanError> {
    if request.profile_cheat_root.as_os_str().is_empty()
        || !request.profile_cheat_root.is_absolute()
    {
        return Err(error(
            CheatInstallPlanErrorKind::DestinationRootUnavailable,
            Some(&request.profile_cheat_root),
            "the selected RetroArch profile declares no absolute cheat directory",
        ));
    }

    let platform_hint = request.platform.as_deref().ok_or_else(|| {
        error(
            CheatInstallPlanErrorKind::DestinationPlatformUnresolved,
            None,
            "the archive has no platform, so no cheat directory can be chosen",
        )
    })?;
    let canonical = canonical_platform_for_alias(platform_hint).ok_or_else(|| {
        error(
            CheatInstallPlanErrorKind::DestinationPlatformUnresolved,
            None,
            format!("platform {platform_hint:?} is not one this build recognizes"),
        )
    })?;
    // Prefer a directory the profile already has. A real RetroArch cheat
    // root is laid out by libretro database name, and installing into a
    // second, differently-named directory for the same system would leave
    // the file somewhere the user does not expect to look, next to - rather
    // than among - the cheat files already there.
    let (platform_directory, platform_directory_source) =
        match existing_platform_directory(&request.profile_cheat_root, canonical) {
            Some(existing) => (
                existing,
                CheatPlatformDirectorySource::ExistingProfileDirectory,
            ),
            None => (
                canonical.to_string(),
                CheatPlatformDirectorySource::CanonicalPlatformName,
            ),
        };

    let (stem, name_source) = strongest_name(request).ok_or_else(|| {
        error(
            CheatInstallPlanErrorKind::DestinationNameUnresolved,
            None,
            "no safe filename could be derived from the content, playlist, or catalogue name",
        )
    })?;
    let file_name = format!("{stem}.cht");

    let assessment = assess_destination(
        &request.profile_cheat_root,
        std::ffi::OsStr::new(&platform_directory),
        std::ffi::OsStr::new(&file_name),
    )
    .map_err(|failure| destination_error(&failure))?;

    Ok(ResolvedCheatDestination {
        path: assessment.proposed_destination.path().to_path_buf(),
        platform_directory,
        platform_directory_source,
        file_name,
        name_source,
        replaces_existing: assessment.destination_state == DestinationState::RegularFile,
        state: assessment.destination_state,
    })
}

/// Finds an existing subdirectory of the profile's cheat root whose name
/// resolves to `canonical`.
///
/// Only real directories are considered, and only their own names are
/// trusted - a name that does not resolve to a canonical platform is
/// ignored, never sanitized into one. Symlinked entries are skipped rather
/// than followed. Ties are broken by name so the choice is deterministic.
fn existing_platform_directory(cheat_root: &Path, canonical: &str) -> Option<String> {
    let mut matches: Vec<String> = Vec::new();
    for entry in fs::read_dir(cheat_root).ok()?.flatten() {
        if matches.len() >= MAX_PLATFORM_DIRECTORY_CANDIDATES {
            break;
        }
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_symlink() || !file_type.is_dir() {
            continue;
        }
        let Some(name) = entry.file_name().to_str().map(str::to_string) else {
            continue;
        };
        if canonical_platform_for_alias(&name) == Some(canonical) && safe_file_stem(&name).is_some()
        {
            matches.push(name);
        }
    }
    matches.sort();
    matches.into_iter().next()
}

fn destination_error(failure: &DestinationSafetyError) -> CheatInstallPlanError {
    CheatInstallPlanError {
        kind: CheatInstallPlanErrorKind::DestinationUnsafe,
        path: Some(failure.path.clone()),
        detail: format!(
            "destination rejected ({:?}) at {}",
            failure.reason,
            failure.path.display()
        ),
    }
}

/// Picks the filename stem in strength order, skipping any candidate that
/// is not a safe single path component.
fn strongest_name(
    request: &CheatDestinationRequest,
) -> Option<(String, CheatDestinationNameSource)> {
    let ordered = [
        (
            request.content_basename.as_deref(),
            CheatDestinationNameSource::ContentBasename,
        ),
        (
            request.playlist_name.as_deref(),
            CheatDestinationNameSource::PlaylistName,
        ),
        (
            Some(request.catalogue_name.as_str()),
            CheatDestinationNameSource::CatalogueName,
        ),
    ];
    ordered.into_iter().find_map(|(value, source)| {
        let stem = safe_file_stem(value?)?;
        Some((stem, source))
    })
}

/// Accepts a value only if it is already a safe, single path component.
/// Deliberately does not strip separators or traversal tokens: laundering
/// an unsafe name into a safe-looking one is exactly how a destination ends
/// up somewhere nobody intended.
fn safe_file_stem(value: &str) -> Option<String> {
    let trimmed = value.trim().trim_end_matches('.').trim();
    if trimmed.is_empty()
        || trimmed == "."
        || trimmed == ".."
        || trimmed.starts_with('.')
        || trimmed.contains(['/', '\\', '\0'])
        || trimmed.chars().any(char::is_control)
        || trimmed.len() > 200
    {
        return None;
    }
    // A `.cht` already on the end would otherwise produce `Game.cht.cht`.
    let trimmed = trimmed
        .strip_suffix(".cht")
        .or_else(|| trimmed.strip_suffix(".CHT"))
        .unwrap_or(trimmed)
        .trim();
    (!trimmed.is_empty()).then(|| trimmed.to_string())
}

