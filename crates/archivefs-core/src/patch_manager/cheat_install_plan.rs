//! Turning one chosen candidate and one cheat selection into a real,
//! installable RetroArch cheat file.
//!
//! This is the step that was missing between the catalogue (read-only) and
//! the shared apply/rollback machinery (which installs *files*, by digest,
//! from an approved source root). Previously the only thing RetroArch cheat
//! installation could do was copy a whole catalogue file verbatim; there was
//! no way to install a chosen subset, because the catalogue parser never
//! kept the cheat codes.
//!
//! The pipeline here is:
//!
//! 1. [`load_candidate_document`] - re-read the chosen candidate from the
//!    verified catalogue root, confirm its digest still matches the one the
//!    candidate list was built from, and parse it with [`super::cht_document`].
//! 2. [`CheatSelection`] - the user's per-cheat choices, which can never
//!    include an entry the parser marked unsafe.
//! 3. [`resolve_cheat_destination`] - the real destination inside the
//!    selected profile's own cheat directory, named from the strongest
//!    available identity, refusing anything that is not provably inside
//!    that directory.
//! 4. [`stage_generated_cheat_file`] - render the file deterministically and
//!    write it into a private staging root, which then acts as the
//!    "approved source root" the existing transaction machinery already
//!    understands.
//! 5. [`build_cheat_install_preview`] - hand that staged file to
//!    [`build_shared_preview`], so backup, atomic write, verification,
//!    journalling, and rollback are the *same* code paths every other
//!    adapter uses rather than a second implementation.
//!
//! The trusted catalogue is only ever read. Nothing in this module writes,
//! renames, or deletes anything under the catalogue root.

