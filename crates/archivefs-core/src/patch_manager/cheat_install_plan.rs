/// Mirrors `cheat_catalogue::MAX_CATALOGUE_FILE_BYTES`.
pub const MAX_CANDIDATE_FILE_BYTES: u64 = 8 * 1024 * 1024;
/// A generated file is only ever a subset of a candidate, so it is bounded
/// by the same figure.
pub const MAX_GENERATED_FILE_BYTES: usize = 8 * 1024 * 1024;
/// The comment written at the top of every generated file. Fixed text, with
/// no timestamp or host detail, so output stays deterministic and carries
/// no environment information into the emulator's directory.
/// Existing platform-directory names examined in one cheat root.
pub const MAX_PLATFORM_DIRECTORY_CANDIDATES: usize = 512;
pub const GENERATED_FILE_PROVENANCE: &str =
    "Generated by ArchiveFS from a verified trusted cheat catalogue.";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum CheatInstallPlanErrorKind {
    /// The candidate path escapes the catalogue root, or is not a single
    /// safe relative path.
    CandidatePathUnsafe,
    CandidateMissing,
    CandidateUnreadable,
    CandidateTooLarge,
    /// The file changed on disk since the candidate list was built.
    CandidateDigestMismatch,
    CandidateUnsupportedEncoding,
    CandidateMalformed,
    /// The candidate is not one the candidate list marked installable.
    CandidateNotInstallable,
    /// Nothing was selected, or everything selected was unsafe.
    NoSelectedCheats,
    /// A selected entry does not exist in the candidate, or is unsafe.
    SelectionInvalid,
    /// The profile declares no usable cheat directory.
    DestinationRootUnavailable,
    /// The platform could not be resolved to a canonical directory name.
    DestinationPlatformUnresolved,
    /// No usable filename could be derived from any available identity.
    DestinationNameUnresolved,
    /// The destination is a symlink, escapes the root, or is otherwise
    /// unsafe. Carries the underlying [`DestinationSafetyError`] reason.
    DestinationUnsafe,
    StagingUnavailable,
    GeneratedFileTooLarge,
    PreviewFailed,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct CheatInstallPlanError {
    pub kind: CheatInstallPlanErrorKind,
    pub path: Option<PathBuf>,
    pub detail: String,
}

impl std::fmt::Display for CheatInstallPlanError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.detail)
    }
}

impl std::error::Error for CheatInstallPlanError {}

fn error(
    kind: CheatInstallPlanErrorKind,
    path: Option<&Path>,
    detail: impl Into<String>,
) -> CheatInstallPlanError {
    CheatInstallPlanError {
        kind,
        path: path.map(Path::to_path_buf),
        detail: detail.into(),
    }
}

