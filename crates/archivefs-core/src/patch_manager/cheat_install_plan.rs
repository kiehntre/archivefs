#[derive(Debug, Clone)]
pub struct CheatInstallPreviewRequest {
    pub selected_archive: PathBuf,
    pub platform: Option<String>,
    /// The verified identity string recorded in the journal and history.
    pub verified_identity: String,
    pub destination: ResolvedCheatDestination,
    pub profile_cheat_root: PathBuf,
    pub staged: StagedCheatFile,
    pub match_strength: PreviewMatchStrength,
}

#[derive(Debug, Clone)]
pub struct CheatInstallPreview {
    pub report: SharedPreviewReport,
    pub destination: ResolvedCheatDestination,
    pub staged: StagedCheatFile,
}

/// Wraps the staged file in the same shared preview every adapter uses, so
/// apply, backup, verification, journalling, and rollback are shared code
/// rather than a parallel implementation.
pub fn build_cheat_install_preview(
    request: &CheatInstallPreviewRequest,
) -> Result<CheatInstallPreview, CheatInstallPlanError> {
    let relative = request
        .destination
        .path
        .strip_prefix(&request.profile_cheat_root)
        .map_err(|_| {
            error(
                CheatInstallPlanErrorKind::DestinationUnsafe,
                Some(&request.destination.path),
                "resolved destination is not inside the profile cheat directory",
            )
        })?
        .to_path_buf();

    let report = build_shared_preview(&SharedPreviewRequest {
        adapter: PreviewAdapter::RetroArch,
        selected_archive: request.selected_archive.clone(),
        platform: request.platform.clone(),
        identity: PreviewIdentity {
            kind: PreviewIdentityKind::RetroArchCatalogueMatch,
            state: PreviewIdentityState::Verified,
            value: Some(request.verified_identity.clone()),
            archive_path: request.selected_archive.clone(),
            revision: None,
        },
        destination_root: request.profile_cheat_root.clone(),
        source_items: vec![PreviewSourceItem {
            adapter: PreviewAdapter::RetroArch,
            source_path: request.staged.path.clone(),
            expected_source_digest: Some(request.staged.digest.clone()),
            destination_relative_paths: vec![relative],
            match_strength: request.match_strength,
        }],
    })
    .map_err(|failure| preview_error(&failure))?;

    Ok(CheatInstallPreview {
        report,
        destination: request.destination.clone(),
        staged: request.staged.clone(),
    })
}

fn preview_error(failure: &SharedPreviewError) -> CheatInstallPlanError {
    CheatInstallPlanError {
        kind: CheatInstallPlanErrorKind::PreviewFailed,
        path: None,
        detail: failure.to_string(),
    }
}

/// Maps a candidate's classification onto the shared preview's own strength
/// vocabulary, and refuses one that must never be installed.
/// Maps a chosen candidate's classification onto the shared preview
/// pipeline's own match-strength vocabulary.
///
/// This is only ever called for a candidate the user has already picked by
/// clicking it explicitly (`CheatWorkflowAction::SelectCandidate`), never
/// for one still sitting unresolved in the candidate list. That distinction
/// matters for `Ambiguous` and `Weak`: `shared_preview`'s own blocking rule
/// (`PreviewMatchStrength::Ambiguous` is always refused - see
/// `shared_preview.rs`) exists to stop an *automatic* process from ever
/// silently picking between tied or weakly-evidenced matches. A human
/// explicitly choosing one of them is exactly the disambiguation that rule
/// is protecting against skipping, so from this point on the chosen
/// candidate is installable the same way a `Strong` one is - never
/// auto-selected (that is decided earlier, in `cheat_candidates`), but no
/// longer blocked by a safety rule aimed at automatic selection.
pub fn match_strength_for_candidate(
    candidate: &CheatCandidate,
) -> Result<PreviewMatchStrength, CheatInstallPlanError> {
    use super::cheat_candidates::CheatCandidateClassification as Classification;
    match candidate.classification {
        Classification::VerifiedExact => Ok(PreviewMatchStrength::VerifiedExact),
        Classification::Strong | Classification::Ambiguous | Classification::Weak => {
            Ok(PreviewMatchStrength::Strong)
        }
        Classification::CrossPlatform | Classification::Unsupported => Err(error(
            CheatInstallPlanErrorKind::CandidateNotInstallable,
            None,
            format!(
                "a {} candidate can never be installed",
                candidate.classification.label().to_lowercase()
            ),
        )),
    }
}

fn hex_sha256(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

