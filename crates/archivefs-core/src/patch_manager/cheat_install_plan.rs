/// One row of the cheat picker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct CheatSelectionEntry {
    /// The source `cheatN_` index. Stable across re-renders, and the key the
    /// GUI uses when toggling.
    pub source_index: u32,
    pub description: String,
    /// Whether this entry may be ticked at all.
    pub selectable: bool,
    /// Whether it is currently ticked - i.e. included in the installed file.
    pub selected: bool,
    /// Whether RetroArch should have it *active* on load. Meaningless when
    /// `selected` is false.
    pub enabled: bool,
    /// Human-readable warnings from the parser, blocking ones first.
    pub warnings: Vec<String>,
    pub has_blocking_warning: bool,
}

/// The whole picker state for one candidate. Construction never selects
/// anything: "no cheats chosen yet" is a real state a user must resolve,
/// not something to guess past by ticking every box.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct CheatSelection {
    pub entries: Vec<CheatSelectionEntry>,
}

impl CheatSelection {
    /// Builds the picker in catalogue order. Nothing is selected; each
    /// entry's `enabled` starts at the source's own `cheatN_enable`, so
    /// ticking a cheat preserves what the catalogue author intended rather
    /// than forcing a project-wide default.
    #[must_use]
    pub fn from_document(document: &ChtDocument) -> Self {
        Self {
            entries: document.entries.iter().map(entry_row).collect(),
        }
    }

    #[must_use]
    pub fn selected_count(&self) -> usize {
        self.entries.iter().filter(|entry| entry.selected).count()
    }

    #[must_use]
    pub fn selectable_count(&self) -> usize {
        self.entries.iter().filter(|entry| entry.selectable).count()
    }

    #[must_use]
    pub fn blocked_count(&self) -> usize {
        self.entries
            .iter()
            .filter(|entry| !entry.selectable)
            .count()
    }

    /// Apply is only available with at least one valid selected cheat.
    #[must_use]
    pub fn can_apply(&self) -> bool {
        self.selected_count() > 0
    }

    /// Ticks one entry. Returns false - changing nothing - when the entry
    /// does not exist or is unsafe, so an unsafe entry can never become
    /// selected through any code path.
    pub fn set_selected(&mut self, source_index: u32, selected: bool) -> bool {
        let Some(entry) = self
            .entries
            .iter_mut()
            .find(|entry| entry.source_index == source_index)
        else {
            return false;
        };
        if selected && !entry.selectable {
            return false;
        }
        entry.selected = selected;
        true
    }

    /// Sets whether a selected cheat starts active in RetroArch.
    pub fn set_enabled(&mut self, source_index: u32, enabled: bool) -> bool {
        let Some(entry) = self
            .entries
            .iter_mut()
            .find(|entry| entry.source_index == source_index && entry.selectable)
        else {
            return false;
        };
        entry.enabled = enabled;
        true
    }

    /// Selects every *selectable* entry. Blocked entries stay untouched.
    pub fn select_all(&mut self) {
        for entry in &mut self.entries {
            if entry.selectable {
                entry.selected = true;
            }
        }
    }

    pub fn clear_all(&mut self) {
        for entry in &mut self.entries {
            entry.selected = false;
        }
    }

    /// The selected entries, in catalogue order, resolved against the
    /// document they came from. Returns an error rather than silently
    /// dropping a selection that no longer resolves.
    pub fn resolve(
        &self,
        document: &ChtDocument,
    ) -> Result<Vec<ChtInstallEntry>, CheatInstallPlanError> {
        let mut resolved = Vec::new();
        for row in self.entries.iter().filter(|entry| entry.selected) {
            let entry = document.entry(row.source_index).ok_or_else(|| {
                error(
                    CheatInstallPlanErrorKind::SelectionInvalid,
                    None,
                    format!(
                        "selected cheat {} is not in the candidate",
                        row.source_index
                    ),
                )
            })?;
            let install = ChtInstallEntry::from_entry(entry, row.enabled).ok_or_else(|| {
                error(
                    CheatInstallPlanErrorKind::SelectionInvalid,
                    None,
                    format!("selected cheat {} is not safe to install", row.source_index),
                )
            })?;
            resolved.push(install);
        }
        if resolved.is_empty() {
            return Err(error(
                CheatInstallPlanErrorKind::NoSelectedCheats,
                None,
                "no cheats are selected; choose at least one before applying",
            ));
        }
        Ok(resolved)
    }
}

fn entry_row(entry: &ChtEntry) -> CheatSelectionEntry {
    let mut warnings: Vec<&super::cht_document::ChtEntryWarning> = entry.warnings.iter().collect();
    warnings.sort_by_key(|warning| !warning.kind.is_blocking());
    CheatSelectionEntry {
        source_index: entry.index,
        description: entry.effective_description(),
        selectable: entry.is_selectable(),
        selected: false,
        enabled: entry.enabled_by_default,
        warnings: warnings
            .iter()
            .map(|warning| warning.detail.clone())
            .collect(),
        has_blocking_warning: entry.blocking_warnings().next().is_some(),
    }
}

