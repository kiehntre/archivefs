// 1. Loading the chosen candidate
// ---------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LoadedCandidate {
    pub absolute_path: PathBuf,
    /// SHA-256 of the exact bytes parsed.
    pub digest: String,
    pub document: ChtDocument,
}

/// Re-reads and parses one candidate from the verified catalogue root.
///
/// The candidate's relative path is validated component by component: an
/// absolute path, a `..` component, or anything that does not land inside
/// the catalogue root is rejected before the file is opened, so a candidate
/// identity that was tampered with in transit cannot address another file.
///
/// `expected_digest` is the digest the candidate list recorded. A mismatch
/// means the catalogue changed underneath the user's choice, and is an
/// error rather than a silent re-selection.
pub fn load_candidate_document(
    catalogue_root: &Path,
    relative_path: &str,
    expected_digest: Option<&str>,
) -> Result<LoadedCandidate, CheatInstallPlanError> {
    let absolute = resolve_catalogue_relative_path(catalogue_root, relative_path)?;

    let metadata = fs::symlink_metadata(&absolute).map_err(|failure| {
        let kind = if failure.kind() == std::io::ErrorKind::NotFound {
            CheatInstallPlanErrorKind::CandidateMissing
        } else {
            CheatInstallPlanErrorKind::CandidateUnreadable
        };
        error(
            kind,
            Some(&absolute),
            format!("candidate unreadable: {failure}"),
        )
    })?;
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Err(error(
            CheatInstallPlanErrorKind::CandidatePathUnsafe,
            Some(&absolute),
            "candidate is a symlink or not a regular file; it is never followed",
        ));
    }
    if metadata.len() > MAX_CANDIDATE_FILE_BYTES {
        return Err(error(
            CheatInstallPlanErrorKind::CandidateTooLarge,
            Some(&absolute),
            format!("candidate exceeds {MAX_CANDIDATE_FILE_BYTES} bytes"),
        ));
    }

    let bytes = fs::read(&absolute).map_err(|failure| {
        error(
            CheatInstallPlanErrorKind::CandidateUnreadable,
            Some(&absolute),
            format!("candidate could not be read: {failure}"),
        )
    })?;
    let digest = hex_sha256(&bytes);
    if let Some(expected) = expected_digest
        && !expected.eq_ignore_ascii_case(&digest)
    {
        return Err(error(
            CheatInstallPlanErrorKind::CandidateDigestMismatch,
            Some(&absolute),
            "candidate file changed since it was matched; re-run matching before installing",
        ));
    }

    let document = parse_cht_bytes(&bytes).map_err(|failure| {
        let kind = match failure.kind {
            ChtParseErrorKind::UnsupportedEncoding
            | ChtParseErrorKind::UnsupportedUtf16Encoding => {
                CheatInstallPlanErrorKind::CandidateUnsupportedEncoding
            }
            ChtParseErrorKind::NotACheatFile | ChtParseErrorKind::TooManyEntries => {
                CheatInstallPlanErrorKind::CandidateMalformed
            }
        };
        error(kind, Some(&absolute), failure.detail)
    })?;

    Ok(LoadedCandidate {
        absolute_path: absolute,
        digest,
        document,
    })
}

/// Joins a catalogue-relative path onto the root, refusing anything that is
/// not a plain relative path of ordinary components.
fn resolve_catalogue_relative_path(
    catalogue_root: &Path,
    relative_path: &str,
) -> Result<PathBuf, CheatInstallPlanError> {
    use std::path::Component;

    if relative_path.trim().is_empty() {
        return Err(error(
            CheatInstallPlanErrorKind::CandidatePathUnsafe,
            Some(catalogue_root),
            "candidate path is empty",
        ));
    }
    let relative = Path::new(relative_path);
    if relative.is_absolute() {
        return Err(error(
            CheatInstallPlanErrorKind::CandidatePathUnsafe,
            Some(relative),
            "candidate path must be relative to the catalogue root",
        ));
    }
    let mut absolute = catalogue_root.to_path_buf();
    for component in relative.components() {
        match component {
            Component::Normal(value) => absolute.push(value),
            _ => {
                return Err(error(
                    CheatInstallPlanErrorKind::CandidatePathUnsafe,
                    Some(relative),
                    "candidate path contains a traversal or root component",
                ));
            }
        }
    }
    if !absolute.starts_with(catalogue_root) {
        return Err(error(
            CheatInstallPlanErrorKind::CandidatePathUnsafe,
            Some(&absolute),
            "candidate path resolves outside the catalogue root",
        ));
    }
    Ok(absolute)
}

