#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StagedCheatFile {
    /// The private root the staged file lives in - passed to
    /// [`super::shared_transaction::build_shared_transaction_plan`] as the
    /// approved source root.
    pub staging_root: PathBuf,
    pub path: PathBuf,
    pub digest: String,
    pub contents: String,
    pub selected_cheat_count: usize,
    pub enabled_cheat_count: usize,
}

/// Renders the selected cheats and writes them into a private staging
/// directory.
///
/// The staging directory is what the transaction machinery treats as the
/// approved source root; it exists because that machinery installs *files*
/// by digest, and a generated subset has no file in the catalogue to point
/// at. The catalogue itself is never written to.
///
/// The write is atomic: content goes to a temporary name in the same
/// directory and is renamed into place, so a staged path never exists in a
/// half-written state.
pub fn stage_generated_cheat_file(
    staging_root: &Path,
    file_name: &str,
    entries: &[ChtInstallEntry],
    extra_comments: &[String],
) -> Result<StagedCheatFile, CheatInstallPlanError> {
    if entries.is_empty() {
        return Err(error(
            CheatInstallPlanErrorKind::NoSelectedCheats,
            None,
            "refusing to stage a cheat file with no cheats in it",
        ));
    }
    let Some(safe_name) = safe_file_stem(file_name) else {
        return Err(error(
            CheatInstallPlanErrorKind::DestinationNameUnresolved,
            None,
            "staged filename is not a safe single path component",
        ));
    };

    let mut comments = vec![GENERATED_FILE_PROVENANCE.to_string()];
    comments.extend(extra_comments.iter().cloned());
    let contents = render_cht_file(entries, &comments);
    if contents.len() > MAX_GENERATED_FILE_BYTES {
        return Err(error(
            CheatInstallPlanErrorKind::GeneratedFileTooLarge,
            None,
            format!("generated cheat file exceeds {MAX_GENERATED_FILE_BYTES} bytes"),
        ));
    }

    fs::create_dir_all(staging_root).map_err(|failure| {
        error(
            CheatInstallPlanErrorKind::StagingUnavailable,
            Some(staging_root),
            format!("staging directory unavailable: {failure}"),
        )
    })?;

    let path = staging_root.join(format!("{safe_name}.cht"));
    let temporary = staging_root.join(format!(".{safe_name}.cht.partial"));
    let mut file = fs::File::create(&temporary).map_err(|failure| {
        error(
            CheatInstallPlanErrorKind::StagingUnavailable,
            Some(&temporary),
            format!("staged file could not be created: {failure}"),
        )
    })?;
    file.write_all(contents.as_bytes())
        .and_then(|()| file.sync_all())
        .map_err(|failure| {
            error(
                CheatInstallPlanErrorKind::StagingUnavailable,
                Some(&temporary),
                format!("staged file could not be written: {failure}"),
            )
        })?;
    drop(file);
    fs::rename(&temporary, &path).map_err(|failure| {
        let _ = fs::remove_file(&temporary);
        error(
            CheatInstallPlanErrorKind::StagingUnavailable,
            Some(&path),
            format!("staged file could not be finalized: {failure}"),
        )
    })?;

    Ok(StagedCheatFile {
        staging_root: staging_root.to_path_buf(),
        path,
        digest: hex_sha256(contents.as_bytes()),
        contents,
        selected_cheat_count: entries.len(),
        enabled_cheat_count: entries.iter().filter(|entry| entry.enabled).count(),
    })
}

